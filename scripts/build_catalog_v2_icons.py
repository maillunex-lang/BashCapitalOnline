#!/usr/bin/env python3
"""Refresh Godot's bundled V2 icon mappings and the matching optional pack."""
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
ASSETS = ROOT / "client/assets"
TARGET = ASSETS / "catalog_v2"
FALLBACKS = {"items": "icon_market", "buildings": "icon_factory", "shops": "icon_shop"}


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def build():
    TARGET.mkdir(exist_ok=True)
    files = {}
    icons = {}
    for kind, fallback in FALLBACKS.items():
        definitions = json.loads((DATA / "catalog_v2" / f"{kind}.json").read_text(encoding="utf-8"))
        for entry in definitions:
            icon = entry["icon"]
            folders = {
                "items": ("icons", "ui"),
                "buildings": ("map", "icons", "ui"),
                "shops": ("ui", "icons"),
            }[kind]
            source = next(
                (ASSETS / folder / f"{icon}.png" for folder in folders
                 if (ASSETS / folder / f"{icon}.png").is_file()),
                ASSETS / "ui" / f"{fallback}.png",
            )
            # Reuse bundled map and UI artwork. Copy only the catalog images
            # needed from the legacy directory, which Godot no longer imports.
            if source.parent.name == "icons":
                source_name = Path("catalog_v2") / source.name
            else:
                source_name = source.relative_to(ASSETS)
            files[source_name.as_posix()] = source.read_bytes()
            icons[icon] = source_name.as_posix()
    for old in TARGET.glob("*.png"):
        if f"catalog_v2/{old.name}" not in files:
            old.unlink()
    for name, content in files.items():
        if name.startswith("catalog_v2/"):
            (ASSETS / name).write_bytes(content)
    manifest = json.dumps(dict(sorted(icons.items())), ensure_ascii=False, indent="\t")
    (TARGET / "icons.gd").write_text(
        "# Generated by scripts/build_catalog_v2_icons.py.\nextends RefCounted\n\n"
        f"const PATHS := {manifest}\n",
        encoding="utf-8",
    )
    files["catalog_v2/icons.json"] = (manifest + "\n").encode("utf-8")

    pack_path = DATA / "packs/catalog_v2_v1.zip"
    with zipfile.ZipFile(pack_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in sorted(files.items()):
            entry = zipfile.ZipInfo(name)
            archive.writestr(entry, content, compress_type=zipfile.ZIP_DEFLATED)
    content = pack_path.read_bytes()
    manifest_path = DATA / "remote_manifest.json"
    remote = json.loads(manifest_path.read_text(encoding="utf-8"))
    packs = [pack for pack in remote["packs"] if pack["id"] not in {"base_art", "catalog_v2"}]
    packs.insert(0, {
        "id": "catalog_v2", "version": 1, "url": f"/api/packs/{pack_path.name}",
        "sha256": hashlib.sha256(content).hexdigest(), "required": False, "size_bytes": len(content),
    })
    remote["packs"] = packs
    remote["style"]["icons"] = "Economy V2 catalog icons with shared fallbacks"
    write_json(manifest_path, remote)
    print(f"{len(icons)} icon mappings, {len(files) - 1} distinct textures, {len(content)} bytes")


if __name__ == "__main__":
    build()
